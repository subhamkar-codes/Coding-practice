import java.util.*;
import java.lang.*;
import java.io.*;

public class Reach_the_Target {
    static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int t = sc.nextInt();
        for (int i = 0; i < t;i++){
            int a = sc.nextInt();
            int b = sc.nextInt();
            int c = a - b;
            System.out.println(c);
        }
    }
}
