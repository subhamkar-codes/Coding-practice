import java.util.*;
import java.lang.*;
import java.io.*;

public class problem_404_Not_Found {
    static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int a = sc.nextInt();
        if (a == 404){
            System.out.println("NOT FOUND");
        }
        else {
            System.out.println("FOUND");
        }
    }
}
